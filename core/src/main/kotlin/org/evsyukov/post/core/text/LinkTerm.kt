package org.evsyukov.post.core.text

/**
 * The Link_Term property of UTS #58 (Unicode Link Detection and Formatting), which decides where a link
 * ends. The values are those of `lib/uts58/constants.rb` in the gem `uts58` 0.2.6 that Mastodon `main`
 * uses (generated there from the UTS #58 17.0.0 data files):
 * - Soft and the paired brackets are listed below;
 * - Hard is unassigned, private-use, surrogate, control and separator code points and a few deprecated
 *   ones;
 * - Include is everything else.
 *
 * Checked against the gem's table for every code point with Unicode 17.0 categories: no difference. The
 * JVM may know an older Unicode version; a code point assigned since then is Hard here.
 */
internal object LinkTerm {

    enum class Kind { INCLUDE, SOFT, OPEN, CLOSE, HARD }

    fun of(cp: Int): Kind {
        if (cp < ASCII.size) return ASCII[cp]
        return classify(cp)
    }

    /** The opening bracket that [close] closes, or -1 when [close] is not a closing bracket. */
    fun openerOf(close: Int): Int {
        var k = 1
        while (k < BRACKETS.size) {
            if (BRACKETS[k] == close) return BRACKETS[k - 1]
            k += 2
        }
        return -1
    }

    private fun classify(cp: Int): Kind {
        if (inRanges(SOFT, cp)) return Kind.SOFT
        for (k in BRACKETS.indices) {
            if (BRACKETS[k] == cp) return if (k % 2 == 0) Kind.OPEN else Kind.CLOSE
        }
        if (cp in HARD_EXCEPTIONS) return Kind.HARD
        return when (Character.getType(cp).toByte()) {
            Character.UNASSIGNED, Character.PRIVATE_USE, Character.SURROGATE, Character.CONTROL,
            Character.SPACE_SEPARATOR, Character.LINE_SEPARATOR, Character.PARAGRAPH_SEPARATOR,
            -> Kind.HARD
            else -> Kind.INCLUDE
        }
    }

    private fun inRanges(ranges: IntArray, cp: Int): Boolean {
        var low = 0
        var high = ranges.size / 2 - 1
        while (low <= high) {
            val middle = (low + high) ushr 1
            when {
                cp < ranges[2 * middle] -> high = middle - 1
                cp > ranges[2 * middle + 1] -> low = middle + 1
                else -> return true
            }
        }
        return false
    }

